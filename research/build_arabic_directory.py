def build():
    book = load_workbook(SOURCE)
    original = load_workbook(SOURCE)
    # Replace structural labels first and keep the table column metadata in sync.
    for old_name, new_name in SHEETS_AR.items():
        ws = book[old_name]
        ws['A1'], ws['A2'] = TITLES_AR[old_name]
        for col, header in enumerate(HEADERS[old_name], 1):
            ws.cell(4, col, header)
        for table in ws.tables.values():
            assert len(table.tableColumns) == len(HEADERS[old_name])
            for col, header in zip(table.tableColumns, HEADERS[old_name]):
                col.name = header
        ws.title = new_name
        ws.sheet_view.rightToLeft = True
        ws.oddFooter.center.text = 'مراجعة المصادر: 2026-10-16 | لم تُؤكد البيانات مباشرة مع المتاجر'
        ws.oddFooter.right.text = 'صفحة &P من &N'
        ws.sheet_properties.tabColor = '087F8C'
        ws.row_dimensions[1].height = 40
        ws.row_dimensions[2].height = 45
        ws.row_dimensions[4].height = 48
    ws = book['إرشادات']
    for row, (topic, explanation) in enumerate(README_AR, 5):
        ws.cell(row, 1, topic)
        ws.cell(row, 2, explanation)
        ws.row_dimensions[row].height = 95 if row in (6, 9, 13, 18, 19) else 80
    for name in ('دليل المتاجر','إدراجات غير مؤكدة'):
        ws = book[name]
        for row in range(5, ws.max_row+1):
            values = SHOPS_AR[ws.cell(row,1).value]
            for col, value in zip((2,3,6,7,8,9), values):
                ws.cell(row,col,value)
            if not str(ws.cell(row,12).value).startswith('https://'):
                ws.cell(row,12,'لم يُرفق — استخدم عنوان المصدر؛ لا توجد نقطة متحققة')
            ws.cell(row,14,'لم يُجرَ تواصل')
            ws.row_dimensions[row].height = 155
    ws = book['أدلة الحقول']
    for row in range(5,ws.max_row+1):
        values = SHOPS_AR[ws.cell(row,1).value]
        ws.cell(row,2,values[0])
        if ws.cell(row,5).value == 'None — not established':
            ws.cell(row,5,'لا يوجد — غير مثبت')
        ws.cell(row,6,values[4])
        ws.cell(row,7,values[5])
        ws.row_dimensions[row].height = 125
    ws = book['المصادر']
    assert len(SOURCE_NOTES_AR) == ws.max_row-4
    for row, (fields, notes) in enumerate(SOURCE_NOTES_AR,5):
        publisher = ws.cell(row,2).value
        ws.cell(row,2,PUBLISHERS_AR.get(publisher,publisher))
        ws.cell(row,3,TYPE_AR[ws.cell(row,3).value])
        ws.cell(row,5,ACCESS_AR[ws.cell(row,5).value])
        ws.cell(row,6,DATES_AR[ws.cell(row,6).value])
        ws.cell(row,8,fields)
        ws.cell(row,9,notes)
        ws.row_dimensions[row].height = 140
    ws = book['سجل التأكيد']
    for row in range(5,ws.max_row+1):
        ws.cell(row,2,SHOPS_AR[ws.cell(row,1).value][0])
        ws.cell(row,5,'لم يُجرَ تواصل')
    ws.data_validations.dataValidation.clear()
    options = 'لم يُجرَ تواصل,محاولة دون رد,مؤكد جزئياً,مؤكد,مغلق أو انتقل'
    validation = DataValidation(type='list',formula1=f'"{options}"')
    validation.errorTitle = 'حالة التواصل'
    validation.error = 'اختر حالة من القائمة.'
    validation.showErrorMessage = True
    ws.add_data_validation(validation)
    validation.add(f'E5:E{ws.max_row}')
    # Right-aligned Arabic; left-to-right phones, URLs, IDs, dates and verbatim
    # excerpts remain unmodified so +961 numbers are readable and copyable.
    for ws in book:
        for row in ws:
            for cell in row:
                if cell.value is None:
                    continue
                font = copy(cell.font)
                font.name = 'Arial'
                cell.font = font
                val = str(cell.value)
                ltr = val.startswith(('https://','+961'))
                if cell.row >= 5:
                    if ws.title == 'المصادر' and cell.column in (1,7,10):
                        ltr = True
                    elif ws.title in ('دليل المتاجر','إدراجات غير مؤكدة') and cell.column in (1,4,5,10,11,12,13):
                        ltr = not (cell.column == 12 and not val.startswith('https://'))
                    elif ws.title == 'أدلة الحقول' and cell.column in (1,3,4,5) and val.startswith(('B','L','S')):
                        ltr = True
                    elif ws.title == 'سجل التأكيد' and cell.column in (1,3,4):
                        ltr = True
                cell.alignment = Alignment(horizontal='left' if ltr else 'right', vertical='top' if cell.row >= 5 else 'center', wrap_text=True, readingOrder=1 if ltr else 2)
        ws.print_area = f'A1:{ws.cell(ws.max_row,ws.max_column).coordinate}'
    book.properties.title = 'دليل متاجر طريق الجديدة — النسخة العربية'
    book.properties.subject = 'معلومات منشورة مع مصادر وحدود تحقق واضحة'
    book.properties.language = 'ar-LB'
    book.properties.description = 'ترجمة للملف الأصلي دون بحث أو تأكيد جديد. المقتطفات الأصلية والأرقام والروابط محفوظة.'
    book.active = 0
    book.save(OUTPUT)
    # Check that translation did not change raw contact details or provenance.
    result = load_workbook(OUTPUT)
    assert result.sheetnames == list(SHEETS_AR.values())
    for old_name, new_name in SHEETS_AR.items():
        before, after = original[old_name], result[new_name]
        assert (before.max_row,before.max_column) == (after.max_row,after.max_column)
        assert after.sheet_view.rightToLeft
        for table in after.tables.values():
            assert [c.name for c in table.tableColumns] == HEADERS[old_name]
        for row in before:
            for cell in row:
                value = cell.value
                if value is not None and (str(value).startswith(('https://','+961')) or cell.is_date):
                    new = after.cell(cell.row,cell.column)
                    assert new.value == value, (old_name,cell.coordinate)
                    assert new.hyperlink == cell.hyperlink
        for row in after:
            for cell in row:
                assert cell.data_type != 'f'
    for row in range(5,result['المصادر'].max_row+1):
        assert result['المصادر'].cell(row,7).value == original['Sources'].cell(row,7).value
    for ws_name in ('دليل المتاجر','إدراجات غير مؤكدة'):
        for row in range(5,result[ws_name].max_row+1):
            assert result[ws_name].cell(row,4).data_type == 's'
            assert result[ws_name].cell(row,14).value == 'لم يُجرَ تواصل'
    with ZipFile(OUTPUT) as archive:
        assert archive.testzip() is None
    original.close()
    book.close()
    result.close()
    print(f'Arabic workbook created and validated: {OUTPUT}')

if __name__ == '__main__':
    build()
